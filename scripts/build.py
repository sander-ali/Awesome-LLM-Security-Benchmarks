CSV_COLUMNS = [
    ("id", lambda b: b["id"]),
    ("name", lambda b: b["name"]),
    ("category", lambda b: b["category"]),
    ("category_slug", lambda b: b["category_slug"]),
    ("year", lambda b: b["year"]),
    ("year_sort", lambda b: b["year_sort"]),
    ("year_venue_origin", lambda b: b["year_venue_origin"]),
    ("year_venue_origin_source", lambda b: b["year_venue_origin_source"]),
    ("website_label", lambda b: b["website"]["label"]),
    ("website_url", lambda b: b["website"]["url"]),
    ("paper_label", lambda b: b["paper"]["label"]),
    ("paper_url", lambda b: b["paper"]["url"]),
    ("security_type", lambda b: b["security_type"]),
    ("details", lambda b: b["details"]),
]


def write_csv(doc: dict) -> None:
    DATA_CSV.parent.mkdir(parents=True, exist_ok=True)
    with DATA_CSV.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, quoting=csv.QUOTE_MINIMAL)
        w.writerow([c[0] for c in CSV_COLUMNS])
        for b in doc["benchmarks"]:
            w.writerow([fn(b) for _, fn in CSV_COLUMNS])


def write_yaml(doc: dict) -> None:
    DATA_YAML.parent.mkdir(parents=True, exist_ok=True)
    DATA_YAML.write_text(to_yaml(doc), encoding="utf-8")


