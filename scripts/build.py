def load() -> dict:
    with DATA_JSON.open(encoding="utf-8") as fh:
        return json.load(fh)


def esc(text: str) -> str:
    """Escape a value for safe use inside a Markdown table cell."""
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def inline(text: str) -> str:
    """Normalize text for use in normal (non-table) Markdown: collapse newlines,
    trim, and leave characters such as '|' untouched."""
    return re.sub(r"\s*\n\s*", " ", (text or "")).strip()


def host_of(url: str) -> str:
    try:
        return urlparse(url).netloc or url
    except Exception:
        return url


def website_short(url: str) -> str:
    """Compact label for the quick-reference table's code column."""
    h = host_of(url)
    path = urlparse(url).path.strip("/")
    if h in ("github.com", "gitlab.com") and path:
        parts = path.split("/")
        return "/".join(parts[:2]) if len(parts) >= 2 else path
    if h == "huggingface.co" and path:
        segs = [s for s in path.split("/") if s]
        return segs[-1] if segs else h
    return h or url


PAPER_TAG_MAP = OrderedDict(
    [
        ("arxiv.org", "arXiv"),
        ("aclanthology.org", "ACL Anthology"),
        ("openreview.net", "OpenReview"),
        ("dl.acm.org", "ACM DL"),
        ("neurips.cc", "NeurIPS"),
        ("proceedings.mlr.press", "PMLR"),
        ("proceedings.iclr.cc", "ICLR"),
        ("huggingface.co", "Hugging Face"),
        ("pages.nist.gov", "NIST"),
    ]
)


def paper_tag(url: str) -> str:
    h = host_of(url)
    for domain, tag in PAPER_TAG_MAP.items():
        if h == domain or h.endswith("." + domain):
            return tag
    return h or "Paper"


# --------------------------------------------------------------------------- #
# YAML emitter (block style; scalars emitted as JSON double-quoted strings,
# which are valid YAML 1.2 scalars). Dependency-free by design.
# --------------------------------------------------------------------------- #
def _scalar(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if v is None:
        return "null"
    return json.dumps(v, ensure_ascii=False)


def _render_map(obj: dict, pad: str) -> list[str]:
    out: list[str] = []
    for k, v in obj.items():
        key = k if re.fullmatch(r"[A-Za-z0-9_\-]+", str(k)) else _scalar(str(k))
        if isinstance(v, dict):
            if v:
                out.append(f"{pad}{key}:")
                out.extend(_render_map(v, pad + "  "))
            else:
                out.append(f"{pad}{key}: {{}}")
        elif isinstance(v, list):
            if v:
                out.append(f"{pad}{key}:")
                out.extend(_render_list(v, pad + "  "))
            else:
                out.append(f"{pad}{key}: []")
        else:
            out.append(f"{pad}{key}: {_scalar(v)}")
    return out


def _render_list(lst: list, pad: str) -> list[str]:
    out: list[str] = []
    for item in lst:
        if isinstance(item, dict) and item:
            lines = _render_map(item, pad + "  ")
            first = lines[0]
            lines[0] = pad + "- " + first[len(pad) + 2:]
            out.extend(lines)
        elif isinstance(item, list) and item:
            out.append(f"{pad}-")
            out.extend(_render_list(item, pad + "  "))
        elif isinstance(item, dict):
            out.append(f"{pad}- {{}}")
        elif isinstance(item, list):
            out.append(f"{pad}- []")
        else:
            out.append(f"{pad}- {_scalar(item)}")
    return out


def to_yaml(doc: dict) -> str:
    header = (
        "# Awesome LLM Security Benchmarks - canonical catalog (YAML view).\n"
        "# Generated by scripts/build.py from data/benchmarks.json - do not edit by hand.\n"
    )
    return header + "\n".join(_render_map(doc, "")) + "\n"


