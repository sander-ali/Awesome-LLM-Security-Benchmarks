def category_sections(doc: dict) -> str:
    out: list[str] = []
    by_cat: "OrderedDict[str, list]" = OrderedDict()
    for c in doc["categories"]:
        by_cat[c["name"]] = []
    for b in doc["benchmarks"]:
        by_cat.setdefault(b["category"], []).append(b)

    for idx, c in enumerate(doc["categories"], start=1):
        items = by_cat.get(c["name"], [])
        out.append(f'<a id="cat-{c["slug"]}"></a>')
        out.append(f"### {idx}. {c['emoji']} {c['name']}")
        out.append("")
        out.append(f"*{c['count']} {'entry' if c['count'] == 1 else 'entries'} · "
                   f"[open category page →](docs/{c['slug']}.md)*")
        out.append("")
        out.append(CATEGORY_TAXONOMY.get(c["name"], CATEGORY_BLURB.get(c["name"], "")))
        out.append("")
        out.append("**In this category:** " + " · ".join(f"[{inline(b['name'])}](#bm-{b['id']})" for b in items))
        out.append("")
        for b in items:
            out.append(detail_entry(b, heading=4))
        out.append("")
    return "\n".join(out)


def docs_page(doc: dict, cat: dict, prev_cat, next_cat) -> str:
    items = [b for b in doc["benchmarks"] if b["category"] == cat["name"]]
    nav = ["[« README](../README.md#top)"]
    if prev_cat:
        nav.append(f"[← {prev_cat['emoji']} {prev_cat['name']}](./{prev_cat['slug']}.md)")
    if next_cat:
        nav.append(f"[{next_cat['emoji']} {next_cat['name']} →](./{next_cat['slug']}.md)")
    header = "\n".join(
        [
            GENERATED_BANNER,
            f"# {cat['emoji']} {cat['name']}",
            "",
            " · ".join(nav),
            "",
            f"> {cat['count']} {'entry' if cat['count'] == 1 else 'entries'} in the "
            f"**{cat['name']}** category of "
            f"[Awesome LLM Security Benchmarks](../README.md#top).",
            "",
            "## Overview",
            "",
            CATEGORY_TAXONOMY.get(cat["name"], CATEGORY_BLURB.get(cat["name"], "")),
            "",
            "## Contents",
            "",
        ]
        + [f"- [{b['id']}. {inline(b['name'])}](#bm-{b['id']}) — {inline(b['year_venue_origin'])}" for b in items]
        + ["", "---", ""]
    )
    body = "\n".join(detail_entry(b, heading=3) for b in items)
    footer = "\n".join(["---", "", " · ".join(nav), ""])
    return header + "\n" + body + "\n" + footer


def docs_index(doc: dict) -> str:
    lines = [
        GENERATED_BANNER,
        "# Documentation Index",
        "",
        "Deep-dive pages, one per category, generated from "
        "[`data/benchmarks.json`](../data/benchmarks.json). "
        "The full catalog lives in the [README](../README.md#top).",
        "",
        "| Category | Entries | Page |",
        "|----------|:------:|------|",
    ]
    for c in doc["categories"]:
        lines.append(
            f"| {c['emoji']} {esc(c['name'])} | {c['count']} | [`docs/{c['slug']}.md`](./{c['slug']}.md) |"
        )
    lines += [
        "",
        "## Machine-readable data",
        "",
        "- [`data/benchmarks.json`](../data/benchmarks.json) — canonical catalog (single source of truth).",
        "- [`data/benchmarks.csv`](../data/benchmarks.csv) — flat export for spreadsheets and dataframes.",
        "- [`data/benchmarks.yaml`](../data/benchmarks.yaml) — the same catalog in YAML.",
        "- [`data/source/Security Benchmarks.xlsx`](<../data/source/Security Benchmarks.xlsx>) — the original workbook.",
        "",
    ]
    return "\n".join(lines)


def write_docs(doc: dict) -> None:
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    cats = doc["categories"]
    for i, c in enumerate(cats):
        prev_cat = cats[i - 1] if i > 0 else None
        next_cat = cats[i + 1] if i < len(cats) - 1 else None
        (DOCS_DIR / f"{c['slug']}.md").write_text(
            docs_page(doc, c, prev_cat, next_cat), encoding="utf-8"
        )
    (DOCS_DIR / "index.md").write_text(docs_index(doc), encoding="utf-8")


