"""
build.py
========

Generate every derived artifact of this repository from the single source of
truth, ``data/benchmarks.json``:

    data/benchmarks.csv     - flat, spreadsheet-friendly export
    data/benchmarks.yaml    - the same catalog in YAML
    docs/<category>.md      - one deep-dive page per category (8 pages)
    docs/index.md           - docs landing page
    README.md               - the full, detailed catalog (the centerpiece)

The generator is deterministic and dependency-free (Python standard library
only). Re-running it after editing ``data/benchmarks.json`` refreshes all of the
above so the docs can never silently drift from the data.

Usage
-----
    python3 scripts/build.py
"""

