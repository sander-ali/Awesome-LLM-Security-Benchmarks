def detail_entry(b: dict, heading: int = 4) -> str:
    """Render one benchmark as a Markdown block (used in README + docs pages)."""
    hashes = "#" * heading
    web = b["website"]
    pap = b["paper"]
    lines = [
        f'<a id="bm-{b["id"]}"></a>',
        f"{hashes} {b['id']}. {b['name']}",
        "",
        f"*{inline(b['year_venue_origin'])}*",
        "",
        f"- **Website / Code:** [{inline(web['label'])}]({web['url']})",
        f"- **Paper:** [{inline(pap['label'])}]({pap['url']})",
        f"- **Security Type Targeted:** {inline(b['security_type'])}",
        "",
        f"{b['details']}",
        "",
        "[↑ Back to top](#top)",
        "",
    ]
    return "\n".join(lines)


def quick_reference_table(doc: dict) -> str:
    rows = [
        "| # | Benchmark | Category | Year | Code | Paper |",
        "|--:|-----------|----------|:----:|------|-------|",
    ]
    cat_emoji = {c["name"]: c["emoji"] for c in doc["categories"]}
    cat_slug = {c["name"]: c["slug"] for c in doc["categories"]}
    for b in doc["benchmarks"]:
        emoji = cat_emoji.get(b["category"], "")
        cslug = cat_slug.get(b["category"], b["category_slug"])
        name = f"[{esc(b['name'])}](#bm-{b['id']})"
        cat = f"[{emoji} {esc(b['category'])}](#cat-{cslug})"
        code = f"[{esc(website_short(b['website']['url']))}]({b['website']['url']})"
        paper = f"[{esc(paper_tag(b['paper']['url']))}]({b['paper']['url']})"
        rows.append(f"| {b['id']} | {name} | {cat} | {esc(b['year'])} | {code} | {paper} |")
    return "\n".join(rows)


def by_the_numbers(doc: dict) -> str:
    bm = doc["benchmarks"]
    meta = doc["metadata"]
    n = len(bm)
    years = [b["year_sort"] for b in bm if b["year_sort"]]
    github = sum(1 for b in bm if "github.com" in b["website"]["url"])
    hf = sum(1 for b in bm if "huggingface.co" in b["website"]["url"] or "huggingface.co" in b["paper"]["url"])
    arxiv = sum(1 for b in bm if "arxiv.org" in b["paper"]["url"])
    acl = sum(1 for b in bm if "aclanthology.org" in b["paper"]["url"])
    openreview = sum(1 for b in bm if "openreview.net" in b["paper"]["url"])

    year_counts = Counter(b["year_sort"] for b in bm if b["year_sort"])
    year_rows = "\n".join(
        f"| {y} | {year_counts[y]} | {'█' * year_counts[y]} |"
        for y in sorted(year_counts)
    )

    return f"""The catalog currently tracks **{n} benchmarks** across **{meta['category_count']} categories**, \
spanning **{min(years)}–{max(years)}**.

| Metric | Value |
|--------|------:|
| Total benchmarks | {n} |
| Categories | {meta['category_count']} |
| Year span | {min(years)}–{max(years)} |
| Entries linking to a GitHub repository | {github} |
| Entries with a Hugging Face artifact | {hf} |
| Papers on arXiv | {arxiv} |
| Papers in the ACL Anthology | {acl} |
| Papers on OpenReview | {openreview} |

**Entries per year**

| Year | Count | |
|-----:|------:|---|
{year_rows}
"""


